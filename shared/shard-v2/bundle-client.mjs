// Reproducible offline packaging of the SAME tested client, including AJV.
// Run after npm ci in aladin_react. No CDN, runtime node_modules or copied reducer.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(resolve(root, 'aladin_react/package.json'));
const { build } = await import(require.resolve('vite'));
await build({
  configFile: false,
  publicDir: false,
  root: resolve(root, 'aladin_react'),
  build: {
    outDir: resolve(root, 'backend_v2/internal/docsurface'), emptyOutDir: false,
    lib: { entry: resolve(root, 'aladin_react/src/modules/doc-surface/data/shard-resource.ts'), formats: ['es'], fileName: () => 'resource-client.generated.js' },
    minify: true,
    rolldownOptions: { external: /^react($|\/)/, output: { banner: '// Generated by shared/shard-v2/bundle-client.mjs; DO NOT EDIT.' } },
  },
});
